function initial(): Lang {
  try {
    const saved = localStorage.getItem(KEY);
    if (saved === 'de' || saved === 'en') return saved;
  } catch {
    // Speicher gesperrt (privates Fenster) – dann nach Browsersprache
  }
  return navigator.language.toLowerCase().startsWith('de') ? 'de' : 'en';
}

export const lang: Lang = initial();
document.documentElement.lang = lang;

/** Neu laden statt jede Ansicht umzuhängen; ein ungesendeter Prompt geht dabei verloren. */
export function setLang(l: Lang): void {
  try {
    localStorage.setItem(KEY, l);
  } catch {
    return;
  }
  location.reload();
}

export function t(key: Key, vars: Record<string, string | number> = {}): string {
  return (lang === 'en' ? en : de)[key].replace(/\{(\w+)\}/g, (m, k: string) => (k in vars ? String(vars[k]) : m));
}

/** Text aus den Map-Dateien: einfach oder { de, en }. */
export function tx(text: Text | undefined): string | undefined {
  return text === undefined || typeof text === 'string' ? text : text[lang];
}
